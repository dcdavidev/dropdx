/**
 * @file src/utils/version.ts
 * Resolution of the installed dropdx CLI version and config version compatibility checks.
 */

import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Reads the `version` field from the nearest `package.json` starting at the
 * directory of this module and walking up towards the package root.
 *
 * @returns dropdx version string, or `0.0.1` when it cannot be resolved.
 */
export function getDropdxVersion(): string {
  try {
    let dir = path.dirname(fileURLToPath(import.meta.url));

    for (let depth = 0; depth < 4; depth++) {
      const pkgPath = path.join(dir, 'package.json');
      if (existsSync(pkgPath)) {
        const json = JSON.parse(readFileSync(pkgPath, 'utf8')) as {
          version?: string;
        };
        if (json.version) {
          return json.version;
        }
      }
      dir = path.dirname(dir);
    }
  } catch {
    // Fall through to the default version below.
  }

  return '0.0.1';
}

/**
 * Builds a warning message when a loaded configuration file was generated by a
 * different dropdx version than the one currently running.
 *
 * @param configVersion - `version` value declared in the config file.
 * @param cliVersion - Currently installed dropdx version.
 * @returns Warning message, or `null` when versions match or are unknown.
 */
export function getConfigVersionWarning(
  configVersion?: string,
  cliVersion: string = getDropdxVersion()
): string | null {
  return !configVersion || configVersion === cliVersion
    ? null
    : `Config file was generated by dropdx v${configVersion}, but you are running dropdx v${cliVersion}. ` +
        'You are using a different config file version, so some options may be missing or behave differently. ' +
        'Run "dropdx init --force" to regenerate the config file for this version.';
}
